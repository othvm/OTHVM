-- OTHVM — model fallback audit log
create table if not exists public.model_fallback_log (
  id bigint generated by default as identity primary key,
  model text not null,
  reason text,
  "timestamp" timestamptz not null default now()
);

create index if not exists model_fallback_log_timestamp_idx
  on public.model_fallback_log ("timestamp" desc);

alter table public.model_fallback_log enable row level security;
